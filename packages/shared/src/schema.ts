// --- Roof faces -------------------------------------------------------------

export type FaceRole =
  | 'main'
  | 'hip_end'
  | 'gable_end_wall'
  | 'dormer'
  | 'sawtooth_pitch'
  | 'sawtooth_glazing'
  | 'mansard_lower'
  | 'mansard_upper'
  | 'gambrel_lower'
  | 'gambrel_upper';

export type Cardinal = 'N' | 'NE' | 'E' | 'SE' | 'S' | 'SW' | 'W' | 'NW' | 'flat';

export type RoofFace = {
  id: string;
  role: FaceRole;
  cardinal: Cardinal;
  /** 3D polygon — vertices carry z (height in metres above ground). */
  geometry: Polygon;
  area_m2: number;
  tilt_deg: number;
  azimuth_deg: number;
  is_pv_eligible: boolean; // default: 0 ≤ tilt ≤ 60° → true
  max_coverage_pct: number; // default 70
  panel_size_m2: number; // default 1.95
};

